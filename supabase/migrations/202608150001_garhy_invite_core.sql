create extension if not exists pgcrypto;

create table if not exists public.events (
  id uuid primary key default gen_random_uuid(),
  slug text not null unique check (slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'),
  event_type text not null check (event_type in ('wedding','engagement','birthday','conference','grand_opening','graduation','vip','corporate','other')),
  title text not null,
  subtitle text,
  timezone text not null default 'Africa/Cairo',
  starts_at timestamptz not null,
  ends_at timestamptz not null,
  rsvp_opens_at timestamptz,
  rsvp_closes_at timestamptz,
  status text not null default 'published' check (status in ('draft','published','cancelled','archived')),
  locale_default text not null default 'ar' check (locale_default in ('ar','en')),
  config jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (ends_at > starts_at)
);

create table if not exists public.guests (
  id uuid primary key default gen_random_uuid(),
  event_id uuid not null references public.events(id) on delete cascade,
  display_name text not null check (char_length(display_name) between 1 and 120),
  phone text,
  email text,
  locale text not null default 'ar' check (locale in ('ar','en')),
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.invitations (
  id uuid primary key default gen_random_uuid(),
  event_id uuid not null references public.events(id) on delete cascade,
  guest_id uuid references public.guests(id) on delete set null,
  token_hash text not null unique,
  max_guests smallint not null default 1 check (max_guests between 1 and 20),
  status text not null default 'active' check (status in ('active','revoked','expired')),
  expires_at timestamptz,
  first_opened_at timestamptz,
  last_opened_at timestamptz,
  open_count integer not null default 0 check (open_count >= 0),
  created_at timestamptz not null default now()
);

create index if not exists invitations_event_idx on public.invitations(event_id);
create index if not exists invitations_guest_idx on public.invitations(guest_id);

create table if not exists public.rsvps (
  id uuid primary key default gen_random_uuid(),
  event_id uuid not null references public.events(id) on delete cascade,
  invitation_id uuid not null references public.invitations(id) on delete cascade,
  attendance text not null check (attendance in ('attending','declining')),
  guest_count smallint not null default 1 check (guest_count between 1 and 20),
  message text check (message is null or char_length(message) <= 1000),
  locale text not null default 'ar' check (locale in ('ar','en')),
  responded_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (invitation_id)
);

create index if not exists rsvps_event_idx on public.rsvps(event_id);

create table if not exists public.guest_passes (
  id uuid primary key default gen_random_uuid(),
  event_id uuid not null references public.events(id) on delete cascade,
  invitation_id uuid not null references public.invitations(id) on delete cascade,
  pass_hash text not null unique,
  pass_hint text not null,
  status text not null default 'active' check (status in ('active','revoked','used','expired')),
  issued_at timestamptz not null default now(),
  used_at timestamptz,
  revoked_at timestamptz
);

create index if not exists guest_passes_event_idx on public.guest_passes(event_id);
create index if not exists guest_passes_invitation_idx on public.guest_passes(invitation_id);

create table if not exists public.event_analytics (
  id bigint generated by default as identity primary key,
  event_id uuid not null references public.events(id) on delete cascade,
  invitation_id uuid references public.invitations(id) on delete set null,
  event_name text not null check (event_name in ('invite_open','rsvp_submit','share','map_open','calendar_add','language_change','pass_issue')),
  locale text check (locale is null or locale in ('ar','en')),
  properties jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists event_analytics_event_created_idx on public.event_analytics(event_id, created_at desc);

